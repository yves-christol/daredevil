const RULE_CATEGORY: [RegExp, CategoryId][] = [
  [/^(color-contrast|link-in-text-block)/, 'contrast'],
  [/^(image-alt|input-image-alt|role-img-alt|svg-img-alt|area-alt|object-alt|image-redundant-alt)$/, 'images'],
  [/^(label|form-field-multiple-labels|autocomplete-valid|select-name|label-title-only)$/, 'forms'],
  [/^(button-name|link-name|input-button-name|label-content-name-mismatch|aria-command-name|aria-input-field-name|aria-toggle-field-name|aria-meter-name|aria-progressbar-name|aria-tooltip-name|aria-treeitem-name|aria-dialog-name|summary-name|frame-title|frame-title-unique|identical-links-same-purpose)$/, 'names'],
  [/^(tabindex|scrollable-region-focusable|nested-interactive|focus-order-semantics|skip-link|accesskeys|target-size|frame-focusable-content|aria-hidden-focus)$/, 'keyboard'],
  [/^(video-caption|audio-caption|no-autoplay-audio|blink|marquee|meta-refresh|meta-refresh-no-exceptions)$/, 'media'],
  [/^(region|bypass|landmark-|page-has-heading-one|heading-order|empty-heading|empty-table-header|list$|listitem|definition-list|dlitem|document-title|html-|valid-lang|duplicate-id|td-|th-|table-|scope-attr-valid|p-as-heading|meta-viewport)/, 'structure'],
  [/^(aria-|presentation-role-conflict|role-)/, 'aria'],
];

/** Fallback by WCAG success criterion, for rules not listed above and for agent findings. */
function categoryFromWcag(wcag: string[] = []): CategoryId | undefined {
  for (const sc of wcag) {
    if (sc === '1.1.1') return 'images';
    if (sc === '1.4.3' || sc === '1.4.11' || sc === '1.4.1' || sc === '1.4.6') return 'contrast';
    if (sc === '2.4.4' || sc === '2.4.6' || sc === '2.5.3') return 'names';
    if (sc.startsWith('3.3.') || sc === '1.3.5') return 'forms';
    if (sc.startsWith('2.1.') || sc === '2.4.3' || sc === '2.4.7' || sc === '2.4.11' || sc === '2.4.1' || sc === '2.5.8') return 'keyboard';
    if (sc.startsWith('1.2.') || sc === '2.2.1' || sc === '2.2.2' || sc === '1.4.2') return 'media';
    if (sc === '1.3.1' || sc === '2.4.2' || sc === '3.1.1' || sc === '3.1.2') return 'structure';
    if (sc === '4.1.2' || sc === '4.1.1') return 'aria';
  }
  return undefined;
}

export function categorizeRule(ruleId: string, wcag: string[] = []): CategoryId {
  for (const [re, cat] of RULE_CATEGORY) if (re.test(ruleId)) return cat;
  return categoryFromWcag(wcag) ?? 'other';
}

export function categorizeFinding(f: AssistedFinding): CategoryId {
  if (f.category === 'alt-quality') return 'images';
  if (f.category === 'keyboard') return 'keyboard';
  if (f.category === 'wording') return categoryFromWcag(f.wcag) === 'forms' ? 'forms' : 'names';
  return categoryFromWcag(f.wcag) ?? 'other';
}

// ------------------------------------------------------------------ plan

interface KeyboardSignal {
  kind: 'no-visible-focus' | 'possible-trap' | 'no-skip-link';
  what: string;
  pages: string[];
}

export interface FixCategory extends CategoryDef {
  /** Branch name suggested for this category's merge request. */
  branch: string;
  groups: IssueGroup[];
  findings: AssistedFinding[];
  keyboardSignals: KeyboardSignal[];
  /** Sum of the groups' estimated score gains (an approximation: gains are not strictly additive). */
  gain: number;
}

const IMPACT_ORDER: Record<string, number> = { critical: 0, serious: 1, moderate: 2, minor: 3 };
const worstImpact = (c: FixCategory): number =>
  Math.min(4, ...c.groups.map((g) => IMPACT_ORDER[g.impact ?? 'moderate']), ...c.findings.map((f) => IMPACT_ORDER[f.impact ?? 'moderate'] ?? 2));

/** Keyboard probe signals, aggregated across pages. Only used when the agent did not review the keyboard itself. */
function keyboardSignals(pages: PageResult[]): KeyboardSignal[] {
  const ok = pages.filter((p) => p.status === 'ok' && p.keyboard);
  const out: KeyboardSignal[] = [];
  const focus = new Map<string, Set<string>>();
  for (const p of ok) for (const n of p.keyboard!.noVisibleFocus) {
    const k = normalizeSelector(n.selector);
    if (!focus.has(k)) focus.set(k, new Set());
    focus.get(k)!.add(p.path);
  }
  for (const [sel, ps] of [...focus].sort((a, b) => b[1].size - a[1].size).slice(0, 10)) {
    out.push({ kind: 'no-visible-focus', what: `\`${sel}\` receives focus with no visible change (WCAG 2.4.7)`, pages: [...ps] });
  }
  for (const p of ok) if (p.keyboard!.possibleTrap) {
    out.push({ kind: 'possible-trap', what: `focus stops moving at \`${p.keyboard!.possibleTrap}\` (possible keyboard trap, WCAG 2.1.2)`, pages: [p.path] });
  }
  const noSkip = ok.filter((p) => !p.keyboard!.hasSkipLink && p.keyboard!.tabbableElements > 20).map((p) => p.path);
  if (noSkip.length) out.push({ kind: 'no-skip-link', what: 'no skip link before a long run of tab stops (WCAG 2.4.1)', pages: noSkip });
  return out;
}

export function buildFixPlan(r: Report, findings: AssistedFinding[] = []): FixCategory[] {
  const cats = new Map<CategoryId, FixCategory>();
  const get = (id: CategoryId) => {
    if (!cats.has(id)) cats.set(id, { ...CATEGORIES[id], branch: `a11y/${id}`, groups: [], findings: [], keyboardSignals: [], gain: 0 });
    return cats.get(id)!;
  };
  for (const g of r.issues) get(categorizeRule(g.ruleId, g.wcag)).groups.push(g);
  for (const f of findings) get(categorizeFinding(f)).findings.push(f);
  if (!findings.some((f) => categorizeFinding(f) === 'keyboard')) {
    const sig = keyboardSignals(r.pages);
    if (sig.length) get('keyboard').keyboardSignals = sig;
  }
  for (const c of cats.values()) {
    c.gain = round(c.groups.reduce((a, g) => a + g.estimatedScoreGain, 0), 2);
    c.findings.sort((a, b) => (IMPACT_ORDER[a.impact ?? 'moderate'] ?? 2) - (IMPACT_ORDER[b.impact ?? 'moderate'] ?? 2));
  }
  // Highest score gain first; then the most severe; 'other' last.
  return [...cats.values()].sort(
    (a, b) => Number(a.id === 'other') - Number(b.id === 'other') || b.gain - a.gain || worstImpact(a) - worstImpact(b),
  );
}

// ------------------------------------------------------------------ markdown

const MAX_HTML = 400;
/** Groups ranked in the top N by gain get two HTML examples, the others one (keeps the prompt compact). */
const TOP_DETAILED = 5;
const oneLine = (s: string) => s.replace(/\s*\n\s*/g, ' ').trim();
const clip = (s: string, n: number) => (s.length > n ? s.slice(0, n) + '…' : s);
const code = (s: string) => {
  const t = oneLine(s);
  const ticks = '`'.repeat(Math.max(1, ...[...t.matchAll(/`+/g)].map((m) => m[0].length + 1)));
  return ticks.length > 1 ? `${ticks} ${t} ${ticks}` : '`' + t + '`';
};
/** Fenced block whose fence is longer than any backtick run inside (site HTML can contain backticks). */
const fence = (lang: string, body: string) => {
  const f = '`'.repeat(Math.max(3, ...[...body.matchAll(/`+/g)].map((m) => m[0].length + 1)));
  return `${f}${lang}\n${body}\n${f}`;
};
const list = (xs: string[], n: number) => xs.slice(0, n).map(code).join(', ') + (xs.length > n ? ` (+${xs.length - n} more)` : '');

function contrastLine(d: Record<string, unknown> | undefined): string {
  if (!d || !d.fgColor) return '';
  return `Colours: text \`${d.fgColor}\` on \`${d.bgColor}\`, ${d.fontSize} ${d.fontWeight}: ratio **${d.contrastRatio}:1**, required **${d.expectedContrastRatio}**.`;
}

function groupTask(g: IssueGroup, ref: string, pagesTotal: number, detailed: boolean): string {
  const out: string[] = [];
  const where = g.pageCount >= Math.max(2, pagesTotal * 0.6) ? `${g.pageCount}/${pagesTotal} pages: likely a shared layout or component` : `${g.pageCount} page(s): ${list(g.pages, 5)}`;
  out.push(`#### ${ref} · ${g.help} (\`${g.ruleId}\`)`, '');
  out.push(
    `- Group id \`${g.id}\` · impact **${g.impact ?? 'moderate'}** · WCAG ${g.wcag.join(', ') || 'none (best practice)'}${g.level !== 'none' ? ` (${g.level})` : ''} · estimated gain ${g.scored ? `+${g.estimatedScoreGain} pts` : 'not scored'}`,
    `- Root cause: ${code(g.signature)} · ${g.occurrences} element(s) on ${where}`,
    `- Selectors: ${list(g.patterns, 4)}`,
    `- Rule reference: ${g.helpUrl}`,
  );
  const ex = g.examples.slice(0, detailed ? 2 : 1);
  if (ex.length) {
    out.push('- Evidence:');
    for (const e of ex) {
      out.push(`  - ${code(e.page)} ${code(e.selector)}`, '', fence('html', clip(oneLine(e.html), MAX_HTML)).replace(/^/gm, '    '), '');
    }
    const fs = ex[0].failureSummary;
    if (fs) out.push(`  - axe: ${oneLine(fs).replace(/^Fix (any|all) of the following:\s*/, '')}`);
    const c = contrastLine(ex[0].data);
    if (c) out.push(`  - ${c}`);
  }
  out.push('');
  return out.join('\n');
}

function findingTask(f: AssistedFinding): string {
  return [
    `#### ${f.id} · ${f.category} (AI-assisted, ${f.confidence ?? 'medium'} confidence)`,
    '',
    `- Impact **${f.impact ?? 'moderate'}**${f.wcag?.length ? ` · WCAG ${f.wcag.join(', ')}` : ''}${f.page ? ` · page ${code(f.page)}` : ''}${f.selector ? ` · ${code(f.selector)}` : ''}`,
    `- Evidence: ${oneLine(f.evidence)}`,
    `- Recommendation: ${oneLine(f.recommendation)}`,
    '',
  ].join('\n');
}

export interface FixPromptOptions {
  findings?: AssistedFinding[];
  /** Absolute path of the report directory (to reference report.json / the re-audit command). */
  reportDir?: string;
  /** Absolute path of the daredevil checkout, where the re-audit command must run. */
  toolDir?: string;
  /** Content of the agent's handoff.md, appended as extra fix guidance. */
  handoffMd?: string;
}

export function fixPromptMarkdown(r: Report, opts: FixPromptOptions = {}): string {
  const plan = buildFixPlan(r, opts.findings);
  const s = r.summary;
  const scopes = scopesOf(r.config);
  const scope = scopes.map((x) => `${x.origin}${x.pathPrefix || '/'}`).join(' + ');
  const reportJson = opts.reportDir ? `${opts.reportDir}/report.json` : 'report.json';
  const authArgs = r.config.auth
    ? ` --auth <session file for that site> ${r.config.imageScreenshots ? '--images' : '--no-images'}${r.config.auth.loggedInCheck ? ` --logged-in-check '${r.config.auth.loggedInCheck.replace(/'/g, "'\\''")}'` : ''}`
    : '';
  // One start URL per scope, in the same order: the re-audit must cover the same set.
  const starts = scopes.length === 1 ? `<url of the site with your changes>${scopes[0].pathPrefix}` : scopes.map((x) => `<url of ${scopeText(x)} with your changes>`).join(' ');
  const reaudit = `npm run -s audit -- ${starts} --same-pages ${reportJson}${authArgs}`;
  const out: string[] = [];

  out.push(`# Fix the accessibility defects found on ${scope}`, '');
  out.push(
    'You are a senior front-end engineer working in the codebase of the website below. An automated accessibility audit (daredevil: axe-core + Playwright, WCAG 2.2 A/AA) found the defects listed in this prompt. Fix them in the source code, and deliver the fixes as **one merge request per category** (pull request on GitHub).',
    '',
  );

  out.push('## Audit context', '');
  out.push(
    `- Site and scope: ${scope} (${s.pagesScanned} pages scanned${s.pagesFailed ? `, ${s.pagesFailed} failed` : ''})`,
    `- Score: **${s.score.overall}/100** (level A ${s.score.byLevel.A}, level AA ${s.score.byLevel.AA}); ${s.violations.nodes} failing elements in ${s.violations.groups} root-cause groups`,
    `- Generated ${r.generatedAt} by daredevil ${r.tool.version} (axe-core ${r.tool.axeVersion}, scoring v${r.tool.scoringVersion})`,
    `- Full data (all elements, pages and examples): \`${reportJson}\`${opts.findings?.length ? `, AI-assisted findings in \`${opts.reportDir ? opts.reportDir + '/' : ''}assisted.json\`` : ''}`,
    '',
    ...(r.config.auth
      ? [
          '- These pages require a login. To re-audit, a person must first save a session for the target site from the daredevil checkout with `npm run -s login -- <url>` (they log in by hand; never ask for or handle their credentials), then pass the session file with `--auth`. Keep the screenshot choice of the original audit (`--images` or `--no-images`, already in the command below): the user decided it, since screenshots can show personal data.',
          '',
        ]
      : []),
    'The selectors and HTML below come from the **rendered** pages. Map each one back to the component, template, stylesheet or content that produces it before editing.',
    '',
  );

  out.push('## How to work', '');
  out.push(
    '1. **Explore first.** For each category below, find where every root cause comes from (search the codebase for class names, ids, attribute values and visible text from the evidence). Most groups map to one shared component or one design token: fix it there once, not per page.',
    '2. **Plan, then confirm.** Before changing code, list the merge requests you intend to open: category, branch, files you expect to touch, and any item you cannot fix in this repository. Ask for confirmation if you were not told to proceed autonomously.',
    '3. **One merge request per category.** Work through the categories in the order given (highest estimated gain first):',
    "   - Create each branch from the up-to-date default branch, using the branch name given in the category heading. MRs must be independent: no MR depends on another one, and none mixes categories.",
    '   - If one change fixes defects of two categories, make it in the first MR and mention it in the other.',
    '   - Skip a category with nothing fixable in this repository, and say why in your final report.',
    '   - Keep commits focused; do not reformat unrelated code.',
    '4. **Verify each MR.** Run the project\'s own build, linters and tests. Check the changed components in a browser with the keyboard (Tab / Shift+Tab / Enter / Space / Escape). Once the change is deployed somewhere (local or staging), re-run the audit from the daredevil checkout' +
      (opts.toolDir ? ` (\`${opts.toolDir}\`)` : '') +
      ':',
    '',
    fence('bash', reaudit),
    '',
    '   A task is **done** when its group id no longer appears in the re-run report and no new group appears in the same component.',
    '5. **Open the merge request** (with `glab mr create` / `gh pr create` if available; otherwise push the branch and give the user the title and description). Use:',
    '   - Title: `a11y(<category>): <what changed>`, for example `a11y(contrast): darken brand orange text to meet 4.5:1`',
    '   - Description: the defects addressed (group ids, rules, WCAG criteria, pages), what changed and why, how it was verified (re-audit result), screenshots for visual changes, and anything left out (third-party widgets, CMS content, design decisions needed).',
    '',
  );

  out.push('## Rules', '');
  out.push(
    '- Fix the cause, never silence the checker: no `aria-hidden` on focusable or meaningful content, no `role="presentation"` / `role="none"` on interactive elements, no removed focus outlines, no deleted content.',
    '- Prefer native HTML elements and attributes over ARIA.',
    '- Keep the visual design unchanged, except colours required for contrast. Report every colour change (old value, new value, ratio).',
    "- Write accessible names and alt text in the page's language, matching the site's tone. Keep the visible text inside the accessible name.",
    '- Third-party widgets (chat, consent banner, embedded players), CMS-authored content and other repositories cannot be fixed here: do not patch generated or vendored files. List these items in the MR description with the exact change to request.',
    '- AI-assisted findings and keyboard-probe signals are heuristics: reproduce each one before fixing it, and drop it (saying so) if it does not reproduce.',
    '',
  );

  out.push('## Merge requests to prepare', '');
  out.push('| # | Category | Branch | Groups | AI findings | Estimated gain |', '|---:|---|---|---:|---:|---:|');
  plan.forEach((c, i) => {
    const extra = c.keyboardSignals.length ? ` (+${c.keyboardSignals.length} probe signals)` : '';
    out.push(`| ${i + 1} | ${c.title} | \`${c.branch}\` | ${c.groups.length} | ${c.findings.length}${extra} | ${c.gain > 0 ? `+${c.gain}` : '0'} |`);
  });
  out.push('', 'Estimated gains are per group and only roughly additive; best-practice and AI-assisted items do not count toward the score.', '');

  const pagesTotal = s.pagesScanned;
  plan.forEach((c, i) => {
    out.push(`## MR ${i + 1}: ${c.title} · branch \`${c.branch}\``, '');
    out.push(c.guidance, '');
    if (c.groups.length) {
      out.push(`### Automated findings (${c.groups.length})`, '');
      c.groups.forEach((g, j) => out.push(groupTask(g, `${i + 1}.${j + 1}`, pagesTotal, r.issues.indexOf(g) < TOP_DETAILED)));
    }
    if (c.findings.length) {
      out.push(`### AI-assisted findings (${c.findings.length})`, '');
      for (const f of c.findings) out.push(findingTask(f));
    }
    if (c.keyboardSignals.length) {
      out.push('### Keyboard probe signals (heuristic, verify first)', '');
      for (const k of c.keyboardSignals) out.push(`- ${k.what}: ${k.pages.length} page(s), e.g. ${list(k.pages, 4)}`);
      out.push('');
    }
  });

  if (r.needsReview.length) {
    out.push(
      '## Not in scope',
      '',
      `axe also reported ${s.needsReview.nodes} elements in ${s.needsReview.groups} groups it could not decide (for example text over images). They are not listed here; fix one only if it is also covered by an AI-assisted finding above.`,
      '',
    );
  }

  if (opts.handoffMd?.trim()) {
    out.push(
      '## Appendix: auditor fix guidance',
      '',
      "The audit agent's detailed notes per group follow. Where they give a more specific fix than above, prefer them. Their task numbering differs from the MR numbering above; match tasks by group id.",
      '',
      opts.handoffMd.trim().replace(/^(#{1,4}) /gm, '$1## '),
      '',
    );
  }

  out.push('## Final report', '', 'When done, list each MR (link or branch), the group ids it fixes, the re-audit score if you ran it, and every item you skipped with the reason.', '');
  return out.join('\n');
}
