/**
 * Fix prompt: a self-contained Markdown prompt that an AI coding agent, working in the
 * audited site's codebase, can act on directly. Findings are bucketed into fix categories,
 * and the prompt asks for one merge request per category, so each MR stays reviewable and
 * touches one kind of code (ARIA in components, colour tokens in CSS, alt text in content…).
 *
 * Built only from report.json (+ assisted.json / handoff.md when the agent produced them):
 * deterministic, regenerated by `audit` and `render`.
 */

export type CategoryId = 'aria' | 'names' | 'forms' | 'images' | 'contrast' | 'structure' | 'keyboard' | 'media' | 'other';

interface CategoryDef {
  id: CategoryId;
  title: string;
  /** Where these fixes usually live, and pitfalls specific to the category. */
  guidance: string;
}

